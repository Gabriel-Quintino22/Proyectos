print("Imported f_oneway from scipy.stats")

"""**Reasoning**:
Now that `f_oneway` is imported, I will extract the `total_sales` for each unique `Tienda` category, perform the one-way ANOVA test, print the F-statistic and p-value, and state the conclusion based on the p-value, as instructed by the subtask.


"""

store_sales = [df['total_sales'][df['Tienda'] == store] for store in df['Tienda'].unique()]
f_stat, p_val = f_oneway(*store_sales)

print(f"F-statistic: {f_stat:.3f}")
print(f"P-value: {p_val:.3f}")

if p_val < 0.05:
    print("There is a statistically significant difference in mean total sales across the different Tienda categories.")
else:
    print("There is no statistically significant difference in mean total sales across the different Tienda categories.")

